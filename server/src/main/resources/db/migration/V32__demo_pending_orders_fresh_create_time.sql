-- =============================================================
-- V32：演示「待支付」订单改为刚创建，便于观察 15 分钟支付倒计时
--
-- 背景：V22 的演示订单里，DEMO-O20260007 / DEMO-O20260008 是
--       status=CREATED + pay_status=UNPAID 的待支付单，但 create_time
--       被设为 NOW() - 4 DAY，远超 15 分钟支付时限。
--       小程序订单列表按「创建时间 + 15 分钟」推算倒计时，
--       结果是剩余时间恒为 0，既看不到倒计时、又与「待支付」状态矛盾。
--
-- 本迁移把这两条待支付演示单的创建时间改为「刚刚」，
-- 使其在小程序里能看到完整的 15 分钟倒计时。
--
-- 幂等：仅更新指定 order_no，可重复执行。
-- 范围：只动 DEMO- 前缀的演示数据，不影响真实业务订单。
-- =============================================================

UPDATE orders
SET create_time = NOW(),
    update_time = NOW()
WHERE order_no IN ('DEMO-O20260007', 'DEMO-O20260008')
  AND status = 'CREATED'
  AND pay_status = 'UNPAID'
  AND deleted = 0;

-- 说明：已支付 / 已完成 / 已取消的演示订单保持原有历史时间不变，
--      避免影响「历史订单」页签的展示与排序验证。