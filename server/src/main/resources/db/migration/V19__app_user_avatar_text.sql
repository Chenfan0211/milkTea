-- 用户头像字段扩容：varchar(255) -> TEXT
-- 原因：头像暂时以 base64 直接存库（方案 B），后续接入腾讯云 COS 后再改回 URL
-- base64 头像远大于 255 字符，需 TEXT 承载
-- =============================================================

ALTER TABLE app_user
    MODIFY COLUMN avatar TEXT NULL COMMENT '用户头像（暂存 base64，后续切 COS 存 URL）';
