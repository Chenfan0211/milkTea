    @BeforeEach
    void database() {
        var db = new EmbeddedDatabaseBuilder().generateUniqueName(true).setType(EmbeddedDatabaseType.H2).build();
        jdbc = new JdbcTemplate(db);
        tx = new TransactionTemplate(new DataSourceTransactionManager(db));
        attribution = new LeaderAttributionService(jdbc);
        admin = new AdminLeaderController(jdbc, attribution);
        internal = new InternalQueryController(null, null, jdbc, null, attribution);
        jdbc.execute("SET MODE MySQL");
        jdbc.execute("create table app_user(id bigint primary key, status int, deleted int)");
        jdbc.execute("create table biz_subject(id bigint primary key, name varchar(40), subject_type varchar(20), status varchar(20), deleted int, bound_user_id bigint)");
        jdbc.execute("create table user_role_grant(id bigint generated by default as identity, user_id bigint, subject_id bigint, role_code varchar(20), status varchar(20), deleted int)");
        jdbc.execute("create table user_leader(id bigint generated by default as identity, user_id bigint unique, leader_user_id bigint, leader_subject_id bigint, binding_source varchar(20), bound_at timestamp, deleted int default 0)");
        jdbc.execute("insert into app_user values (1,1,0),(2,1,0),(3,1,0)");
        jdbc.execute("insert into biz_subject values (20,'A','LEADER','active',0,null),(30,'B','LEADER','active',0,null)");
        jdbc.execute("insert into user_role_grant(user_id,subject_id,role_code,status,deleted) values (2,20,'LEADER','active',0),(3,30,'LEADER','active',0)");
    }

    @Test
    void inactiveSubjectIsNeitherSelfNorEffectiveRelation() {
        tx.executeWithoutResult(s -> admin.assignLeader(Map.of("userId", 1, "leaderUserId", 2)));
        jdbc.update("update biz_subject set status='inactive' where id=20");
        assertThat(internal.userLeader(1L).get("leaderUserId")).isNull();
        assertThat(internal.userLeader(2L).get("leader")).isEqualTo(false);
        assertThatThrownBy(() -> tx.executeWithoutResult(s -> admin.assignLeader(Map.of("userId", 1, "leaderUserId", 2))))
                .isInstanceOf(BusinessException.class);
    }

    @Test
    void disablingLeavesSubjectAndGrantForHistory() {
        tx.executeWithoutResult(s -> admin.removeLeader(20L));
        assertThat(jdbc.queryForObject("select status from biz_subject where id=20 and deleted=0", String.class))
                .isEqualTo("inactive");
        assertThat(jdbc.queryForObject("select count(*) from user_role_grant where subject_id=20 and deleted=0", Long.class))
                .isEqualTo(1L);
    }

    @Test
    void firstValidShareWinsUntilInvalidOrReboundByAdmin() {
        assertThat(bind(1L, 2L)).isEqualTo(2L);
        assertThat(bind(1L, 2L)).isEqualTo(2L);
        assertThat(bind(1L, 3L)).isEqualTo(2L);
        assertThat(jdbc.queryForObject("select binding_source from user_leader where user_id=1", String.class)).isEqualTo("SHARE");
        tx.executeWithoutResult(s -> admin.assignLeader(Map.of("userId", 1, "leaderUserId", 3)));
        assertThat(bind(1L, 2L)).isEqualTo(3L);
        assertThat(jdbc.queryForObject("select binding_source from user_leader where user_id=1", String.class)).isEqualTo("ADMIN");
        jdbc.update("update user_role_grant set status='inactive' where user_id=3");
        assertThat(bind(1L, 2L)).isEqualTo(2L);
        assertThatThrownBy(() -> bind(1L, 3L)).isInstanceOf(BusinessException.class);
        assertThatThrownBy(() -> bind(2L, 2L)).isInstanceOf(BusinessException.class);
    }

    @Test
    void concurrentShareLinksReturnTheSameWinner() throws Exception {
        var pool = Executors.newFixedThreadPool(2);
        try {
            var a = pool.submit(() -> bind(1L, 2L));
            var b = pool.submit(() -> bind(1L, 3L));
            assertThat(a.get()).isEqualTo(b.get()).isIn(2L, 3L);
            assertThat(jdbc.queryForObject("select count(*) from user_leader where user_id=1", Long.class)).isEqualTo(1L);
        } finally {
            pool.shutdownNow();
        }
    }

    @Test
    void splitReflectsPendingPartialAndFullRefundsAlongsideFundedRecords() {
        createSplitFixture();
        jdbc.execute("insert into settlement_record values "
                + "(101,4,40,100,50,50,'SETTLED',0),(102,4,40,null,150,null,'SETTLED',0),"
                + "(103,4,50,500,250,250,'PENDING',0),(104,4,20,null,50,50,'PENDING',0)");
        jdbc.execute("insert into fund_flow values "
                + "('MO1','out','PLATFORM','REFUND',50,0,101),('MO1','out','PLATFORM','REFUND',150,0,102)");
        assertThat(internal.splitSnapshot("MO1"))
                .containsEntry("platformShare", 400L).containsEntry("costTotal", 500L).containsEntry("leaderShare", 100L)
                .containsEntry("refundPlatform", 200L).containsEntry("refundSupplier", 250L).containsEntry("refundLeader", 50L)
                .containsEntry("netPlatform", 200L).containsEntry("netSupplier", 250L).containsEntry("netLeader", 50L);

        jdbc.execute("insert into fund_flow values "
                + "('MO1','out','PLATFORM','REFUND',50,0,101),('MO1','out','PLATFORM','REFUND',150,0,102)");
        jdbc.update("update settlement_record set status='CANCELED' where order_id=4");
        assertThat(internal.splitSnapshot("MO1"))
                .containsEntry("refundPlatform", 400L).containsEntry("refundSupplier", 500L).containsEntry("refundLeader", 100L)
                .containsEntry("netPlatform", 0L).containsEntry("netSupplier", 0L).containsEntry("netLeader", 0L);
    }

    @Test
    void legacySnapshotWithoutSettlementRecordsFallsBackToPostedReversals() {
        createSplitFixture();
        jdbc.execute("insert into fund_flow values ('MO1','out','PLATFORM','REFUND',50,0,null),('MO1','out','PLATFORM','REFUND',150,0,null),('MO1','out','SUPPLIER','REFUND',250,0,null),('MO1','out','LEADER','REFUND',50,0,null),('MO1','out','LEADER','REFUND',50,1,null),('MO1','in','LEADER','SPLIT',100,0,null),('MO2','out','LEADER','REFUND',100,0,null)");
        assertThat(internal.splitSnapshot("MO1"))
                .containsEntry("platformShare", 400L).containsEntry("costTotal", 500L).containsEntry("leaderShare", 100L)
                .containsEntry("refundPlatform", 200L).containsEntry("refundSupplier", 250L).containsEntry("refundLeader", 50L)
                .containsEntry("netPlatform", 200L).containsEntry("netSupplier", 250L).containsEntry("netLeader", 50L);

        jdbc.execute("insert into fund_flow values ('MO1','out','PLATFORM','REFUND',200,0,null),('MO1','out','SUPPLIER','REFUND',250,0,null),('MO1','out','LEADER','REFUND',50,0,null)");
        assertThat(internal.splitSnapshot("MO1"))
                .containsEntry("netPlatform", 0L).containsEntry("netSupplier", 0L).containsEntry("netLeader", 0L);
    }
